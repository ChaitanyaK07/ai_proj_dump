"""Writes results/summary.md: every number in it is read from a result file, which it names."""
from __future__ import annotations

import json
import math
from pathlib import Path

import pandas as pd


def md_table(df: pd.DataFrame, floatfmt: str = "{:.3g}") -> str:
    def fmt(v):
        if isinstance(v, float):
            if math.isnan(v):
                return ""
            return floatfmt.format(v)
        return str(v)
    head = "| " + " | ".join(str(c) for c in df.columns) + " |"
    sep = "|" + "|".join("---" for _ in df.columns) + "|"
    body = ["| " + " | ".join(fmt(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join([head, sep, *body])


def _read(path: Path):
    return pd.read_csv(path) if path.exists() else None


def write_summary(results: Path) -> Path:
    lines = ["# Results summary", "",
             "Generated by `python -m wayfinder evaluate`. Every table below is copied from the file named "
             "under it; nothing here is typed by hand.", ""]

    gng = results / "go_no_go.json"
    if gng.exists():
        g = json.loads(gng.read_text(encoding="utf-8"))
        lines += ["## Week-4 go / no-go", "",
                  f"**Verdict: {g['verdict']}** — {g['headline']}.", ""]
        lines += ["* median expansions: " + ", ".join(f"{k} = {v:g}" for k, v in g["median_expanded"].items()
                                                         if v is not None)]
        if "expansion_reduction_vs_astar_hadm_pct" in g:
            pct = g["expansion_reduction_vs_astar_hadm_pct"]
            lines += [f"* learned Focal vs A*(h_adm): {pct:.1f}% fewer expansions"]
        lines += ["* learned beats the tuned classical guide at the same W: "
                  f"{g['learned_beats_tuned_classical_same_W']}",
                  f"* learned beats weighted A* at the same W: {g['learned_beats_wastar_same_W']}"]
        if "perfect_guide_reduction_vs_astar_hadm_pct" in g:
            lines += [f"* ceiling — Focal with the perfect guide h* vs A*(h_adm): "
                      f"{g['perfect_guide_reduction_vs_astar_hadm_pct']:.1f}% fewer expansions"]
        lines += ["", "GO requires beating both A*(h_adm) and the tuned classical guide at the same W.", "",
                  "Source: `results/go_no_go.json`", ""]

    curve = _read(results / "problem_curve.csv")
    if curve is not None:
        cols = ["lambda", "rho_min"] + [c for c in curve.columns if c.endswith("_mean")] + \
               [c for c in curve.columns if c.endswith("/dijkstra")] + ["informedness_hadm_source"]
        lines += ["## 1. The problem as a measurement", "",
                  "Mean states expanded per query as weight moves from walking time to the non-distance sliders "
                  "(`w = (1-λ, λ/4, λ/4, λ/4, λ/4)`), on the 200 frozen OD pairs.", "",
                  md_table(curve[[c for c in cols if c in curve.columns]]), "",
                  "Source: `results/problem_curve.csv`, figure `results/plots/problem_curve.png`", ""]

    summ = _read(results / "benchmark_summary.csv")
    if summ is not None:
        cols = ["group", "W", "runs", "expanded_median", "expanded_q25", "expanded_q75", "focal_floor_median",
                "generated_median",
                "latency_ms_median", "latency_ms_p95", "subopt_mean", "subopt_max", "optimal_rate",
                "bound_violations", "seed_medians_expanded"]
        lines += ["## 2. Frozen benchmark (200 queries)", "",
                  "Median and inter-quartile range over queries; learned conditions pool three training seeds "
                  "(per-seed medians in the last column). Suboptimality is cost / exact optimum. "
                  "`focal_floor_median` is the number of states any Focal Search with that W must expand, "
                  "whatever its guide (states with g* + h_adm < C*/W).", "",
                  md_table(summ[[c for c in cols if c in summ.columns]]), "",
                  "Source: `results/benchmark_summary.csv` (per-run rows in `results/benchmark_raw.csv`), "
                  "figures `results/plots/expansions_vs_W.png`, `results/plots/latency.png`", ""]

    bound = _read(results / "bound_sweep.csv")
    if bound is not None:
        b = bound.groupby(["family", "W"]).agg(queries=("queries", "sum"), achieved_mean=("achieved_mean", "mean"),
                                               achieved_max=("achieved_max", "max"),
                                               bound_violations=("bound_violations", "sum")).reset_index()
        lines += ["## 3. Guaranteed vs achieved suboptimality", "",
                  md_table(b), "",
                  f"Total bound violations across the sweep: **{int(bound['bound_violations'].sum())}**.", "",
                  "Source: `results/bound_sweep.csv`, figure `results/plots/bound_guaranteed_vs_achieved.png`", ""]

    qual = _read(results / "heuristic_quality.csv")
    if qual is not None:
        lines += ["## 4. Heuristic quality", "",
                  "Admissibility violations (h > h*), consistency violations (h(u) > c(u,v) + h(v)) and "
                  "informedness h / h*, averaged over the benchmark queries.", "",
                  md_table(qual), "",
                  "Source: `results/heuristic_quality.csv`, figure `results/plots/informedness_hist.png`", ""]

    lab = _read(results / "training" / "label_metrics.csv")
    gen = _read(results / "generalisation.csv")
    if lab is not None or gen is not None:
        lines += ["## 5. Generalisation to held-out weight vectors", ""]
        if lab is not None:
            lines += ["Label-level (unseen test targets):", "", md_table(lab), "",
                      "Source: `results/training/label_metrics.csv`", ""]
        if gen is not None:
            cols = ["group", "weight_set", "runs", "expanded_median", "subopt_mean", "subopt_max", "bound_violations"]
            g2 = gen[gen["family"].isin(["focal_learned", "focal_tuned", "astar_learned", "astar_hadm"])]
            lines += ["Search-level (benchmark split by weight set):", "",
                      md_table(g2[[c for c in cols if c in g2.columns]]), "",
                      "Source: `results/generalisation.csv`, figure `results/plots/generalisation.png`", ""]

    hp = _read(results / "training" / "hparam_search.csv")
    if hp is not None:
        lines += ["## 6. Training", "", "Hyperparameter pass (validation MSE of log ratio):", "", md_table(hp), "",
                  "Source: `results/training/hparam_search.csv`, logs `results/training/train_log_seed*.csv`, "
                  "figure `results/plots/training_curves.png`", ""]

    us = _read(results / "user_study" / "summary.csv")
    lines += ["## 7. User study", ""]
    if us is not None:
        lines += [md_table(us), "",
                  "Agreement = share of choices for the preference route. No statistical significance is claimed "
                  "at this sample size; weight combinations other than the three profiles are algorithmically "
                  "correct but behaviourally untested.", "", "Source: `results/user_study/summary.csv`", ""]
    else:
        lines += ["No responses analysed yet: run the study page (`/study`) and then "
                  "`python -m wayfinder study-analyze`.", ""]

    out = results / "summary.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    return out
